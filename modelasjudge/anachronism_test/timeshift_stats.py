"""timeshift_stats.py — how far in time each ablation moves a question's context.

Compares two candidate-frame ablations against the true source dates:

  wrongframe   the permuted-context run in the paper ("GPT-5.4 wrong
               contexts"). Its derangement is regenerated here with
               build_candidate_frame_variant.py's permute mode and the original
               seed, which reproduces the original build exactly (checked
               866/866 against GPT-1914/.../chronologic_en_0.8_wrongcontext.jsonl;
               0.8 and 1.0 are identical in every field involved).
  anachronism  every context moved to TARGET_YEAR (2023).

The "date" of a frame is the source_date of the question it belongs to (for
wrongframe, the donor question's source_date). Writes timeshift_stats.md next
to this script.

    python timeshift_stats.py [--benchmark ../../booksample/chronologic_en_1.0.jsonl]
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import statistics
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
TARGET_YEAR = 2023
GROUP = {  # substantive/groups.py
    "phrase_cloze": "cloze", "sentence_cloze": "cloze", "topic_sentence": "cloze",
    "constrained_generation": "generation", "character_modeling": "generation",
    "knowledge": "knowledge/inference", "inference": "knowledge/inference",
    "abstention": "knowledge/inference",
}
TYPE_ORDER = ["phrase_cloze", "sentence_cloze", "topic_sentence", "constrained_generation",
              "character_modeling", "knowledge", "inference", "abstention"]
GROUP_ORDER = ["cloze", "generation", "knowledge/inference"]


def _builder():
    path = REPO / "booksample" / "build_candidate_frame_variant.py"
    spec = importlib.util.spec_from_file_location("build_candidate_frame_variant", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def year(rec) -> int:
    return int(str(rec["source_date"])[:4])


def pct(xs, p):
    xs = sorted(xs)
    k = (len(xs) - 1) * p / 100
    lo, hi = int(k), min(int(k) + 1, len(xs) - 1)
    return xs[lo] + (xs[hi] - xs[lo]) * (k - lo)


def summarize(xs):
    return {"n": len(xs), "mean": statistics.mean(xs), "median": statistics.median(xs),
            "sd": statistics.pstdev(xs), "p10": pct(xs, 10), "p90": pct(xs, 90),
            "min": min(xs), "max": max(xs),
            "lt10": sum(x < 10 for x in xs) / len(xs), "lt25": sum(x < 25 for x in xs) / len(xs)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--benchmark", type=Path, default=REPO / "booksample" / "chronologic_en_1.0.jsonl")
    ap.add_argument("--out", type=Path, default=HERE / "timeshift_stats.md")
    args = ap.parse_args()

    b = _builder()
    records = b.load_records(args.benchmark)
    variant = b.permuted_variant(records, "wrongframe", seed=20260824, max_tries=5000)
    by_q = {r["question_number"]: r for r in records}

    wf, an = defaultdict(list), defaultdict(list)
    signed, cross = [], defaultdict(int)
    for v in variant:
        donor = by_q[v["candidate_frame_source_qnum"]]
        d = year(donor) - year(v)
        rt = v["reasoning_type"]
        for key in (rt, GROUP[rt], "ALL"):
            wf[key].append(abs(d))
            an[key].append(TARGET_YEAR - year(v))
        signed.append(d)
        if donor["reasoning_type"] != rt:
            cross[rt] += 1
    W, A = summarize(wf["ALL"]), summarize(an["ALL"])
    years = [year(r) for r in records]

    L = []
    L.append("# Temporal displacement: wrongframe vs. anachronism\n")
    L.append(f"Generated by `timeshift_stats.py` from `{args.benchmark.name}` "
             f"({len(records)} questions; source dates {min(years)}–{max(years)}, "
             f"median {statistics.median(years):.0f}). Displacement = |year of the frame the "
             f"candidate saw − true source year|. For wrongframe, the frame's year is the donor "
             f"question's source date; for anachronism it is {TARGET_YEAR}.\n")
    L.append("## Headline\n")
    L.append("| | mean | median | SD | 10th–90th pct | min–max | share < 10 yrs | share < 25 yrs |")
    L.append("|---|---|---|---|---|---|---|---|")
    for name, s in (("wrongframe (permuted)", W), (f"anachronism ({TARGET_YEAR})", A)):
        L.append(f"| {name} | {s['mean']:.1f} | {s['median']:.0f} | {s['sd']:.1f} | "
                 f"{s['p10']:.0f}–{s['p90']:.0f} | {s['min']}–{s['max']} | "
                 f"{s['lt10']:.1%} | {s['lt25']:.1%} |")
    L.append("")
    later = sum(d > 0 for d in signed) / len(signed)
    L.append(f"- The anachronism frames move contexts **{A['mean'] / W['mean']:.1f}×** farther "
             f"on average than permutation did ({A['mean']:.0f} vs. {W['mean']:.1f} years), and "
             f"never by less than {A['min']} years. Under permutation, {W['lt10']:.0%} of "
             f"questions moved less than a decade and {W['lt25']:.0%} less than 25 years.")
    L.append(f"- Permutation was roughly symmetric: {later:.0%} of donors were later than the "
             f"true source, {sum(d < 0 for d in signed) / len(signed):.0%} earlier, "
             f"{sum(d == 0 for d in signed) / len(signed):.0%} the same year (signed mean "
             f"{statistics.mean(signed):+.1f} yrs). Anachronism always moves forward.")
    L.append(f"- Permutation drew donors within four `frame_type` buckets (world / character / "
             f"other book / passage), **not** within reasoning type: "
             f"{sum(cross.values())}/{len(records)} questions "
             f"({sum(cross.values()) / len(records):.0%}) got a frame from a different "
             f"reasoning type. So the wrongframe frames also changed genre, nationality, author "
             f"and sometimes the instruction wording, not just the date.\n")

    def table(keys, title):
        L.append(f"## By {title}\n")
        L.append("| | n | wrongframe mean | wrongframe median | < 10 yrs | anachronism mean | "
                 "anachronism min | ratio | donors from other reasoning type |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        for k in keys:
            w, a = summarize(wf[k]), summarize(an[k])
            c = (sum(cross[t] for t in TYPE_ORDER if GROUP[t] == k) if k in GROUP_ORDER
                 else cross[k])
            L.append(f"| {k} | {w['n']} | {w['mean']:.1f} | {w['median']:.0f} | {w['lt10']:.0%} | "
                     f"{a['mean']:.1f} | {a['min']} | {a['mean'] / w['mean']:.1f}× | "
                     f"{c}/{w['n']} |")
        L.append("")

    table(GROUP_ORDER, "score group (as reported in the paper)")
    table(TYPE_ORDER, "reasoning type")

    L.append("## Draft sentence for the reviewer response\n")
    L.append(f"> In the permuted-context ablation, the frame a model saw was displaced from the "
             f"true source date by {W['mean']:.0f} years on average (median {W['median']:.0f}; "
             f"{W['lt10']:.0%} of questions by less than a decade), because all but "
             f"{sum(y < 1831 for y in years)} of the {len(years)} sources fall between 1831 "
             f"and 1930. The "
             f"anachronism ablation moves every frame to {TARGET_YEAR}: a mean displacement of "
             f"{A['mean']:.0f} years (minimum {A['min']}), about {A['mean'] / W['mean']:.0f}× "
             f"larger, and it also strips authorship, nationality, stance, profession and "
             f"gender cues from the frame.\n")
    args.out.write_text("\n".join(L), encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
